"""Carry local code to the Colab runtime without git.

The Colab kernel runs on a remote machine that cannot see the laptop's disk.
Only notebook cells travel there. So this module packs the project's code
into one notebook cell as a base64 zip. Running that cell on Colab unpacks
the code and installs it. cpp/build is never packed; the C++ is compiled on the runtime.

Local use, after editing code and before running a notebook:

    python -m vggt_aura.sync            # refresh the sync cell in every notebook
    python -m vggt_aura.sync --check    # exit 1 if any notebook carries stale code
    python -m vggt_aura.sync --clear    # empty the sync cells again (the state notebooks are committed in)

Notebooks are COMMITTED with empty sync cells: the code lives in src/, cpp/ and tests/ once, not as a
copy inside every notebook. A notebook with an empty sync cell stops at that cell and says what to run.

The zip is deterministic, so the same code always gives the same hash. The
hash is printed locally and again by the cell on Colab. If the two differ,
the runtime is running old code.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
import sys
import zipfile
from pathlib import Path

MARKER = "# === CODE SYNC (auto-generated by `python -m vggt_aura.sync`, do not edit) ==="
RUNTIME_DIR = "/content/vggt-omega-aura-benchmark"

INCLUDE_DIRS = ("src", "cpp", "tests")   # tests travel too, so the differential suite can run on the runtime
INCLUDE_FILES = ("pyproject.toml",)
SKIP_DIR_NAMES = {"__pycache__", "build", ".pytest_cache", ".ipynb_checkpoints"}
SKIP_SUFFIXES = {".pyc", ".pyd", ".so", ".o", ".pt", ".pth"}


def collect_files(project_root) -> list[Path]:
    """Files to ship, as sorted paths relative to the project root."""
    root = Path(project_root)
    found = []
    for name in INCLUDE_FILES:
        if (root / name).is_file():
            found.append(Path(name))
    for directory in INCLUDE_DIRS:
        for path in sorted((root / directory).rglob("*")):
            relative = path.relative_to(root)
            if not path.is_file():
                continue
            if any(part in SKIP_DIR_NAMES or part.endswith(".egg-info") for part in relative.parts):
                continue
            if path.suffix in SKIP_SUFFIXES or path.name.startswith(".env"):
                continue
            found.append(relative)
    return sorted(found, key=lambda p: p.as_posix())


def build_payload(project_root) -> tuple[str, str, int]:
    """Return (base64 zip, short sha256 of the zip, file count)."""
    root = Path(project_root)
    files = collect_files(root)
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for relative in files:
            info = zipfile.ZipInfo(relative.as_posix(), date_time=(2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            # Normalise line endings so Windows and Linux give the same hash.
            data = (root / relative).read_bytes().replace(b"\r\n", b"\n")
            archive.writestr(info, data)
    raw = buffer.getvalue()
    return base64.b64encode(raw).decode("ascii"), hashlib.sha256(raw).hexdigest()[:12], len(files)


def render_sync_cell(payload: str, digest: str, count: int) -> str:
    wrapped = "\n".join(payload[i:i + 100] for i in range(0, len(payload), 100))
    return f'''{MARKER}
# code hash: {digest} | files: {count}
import base64, io, os, shutil, subprocess, sys, zipfile
from pathlib import Path

PROJECT_DIR = Path("{RUNTIME_DIR}")
PAYLOAD = """
{wrapped}
"""
for stale in {list(INCLUDE_DIRS)!r}:  # drop old code, keep results/
    shutil.rmtree(PROJECT_DIR / stale, ignore_errors=True)
PROJECT_DIR.mkdir(parents=True, exist_ok=True)
zipfile.ZipFile(io.BytesIO(base64.b64decode(PAYLOAD))).extractall(PROJECT_DIR)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-e", str(PROJECT_DIR)], check=True)
if str(PROJECT_DIR / "src") not in sys.path:
    sys.path.insert(0, str(PROJECT_DIR / "src"))
for name in [m for m in sys.modules if m == "vggt_aura" or m.startswith("vggt_aura.")]:
    del sys.modules[name]  # a re-run picks up new code without a kernel restart
os.environ["VGGT_AURA_CODE_HASH"] = "{digest}"  # start_session writes it into provenance.jsonl
print("code hash {digest} | {count} files unpacked to", PROJECT_DIR)'''


EMPTY_SYNC_CELL = MARKER + chr(10) + ('raise RuntimeError("The sync cell is empty. On your own machine, in the project folder, '
                                      'run:  python -m vggt_aura.sync   and reopen this notebook.")')


def _cell_text(cell) -> str:
    source = cell.get("source", "")
    return "".join(source) if isinstance(source, list) else source


def update_notebook(notebook_path, cell_source: str, write: bool = True) -> str:
    """Replace the sync cell. Returns 'updated', 'current' or 'no-sync-cell'."""
    path = Path(notebook_path)
    notebook = json.loads(path.read_text(encoding="utf-8"))
    for cell in notebook["cells"]:
        if cell["cell_type"] == "code" and _cell_text(cell).startswith(MARKER):
            if _cell_text(cell) == cell_source:
                return "current"
            if write:
                cell["source"] = cell_source.splitlines(keepends=True)
                cell["outputs"] = []
                cell["execution_count"] = None
                path.write_text(json.dumps(notebook, indent=1) + "\n", encoding="utf-8")
            return "updated"
    return "no-sync-cell"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Pack local code into the notebooks' sync cell.")
    parser.add_argument("--root", default=".", help="project root, default: current directory")
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 if any notebook is stale")
    parser.add_argument("--clear", action="store_true", help="empty every sync cell (the state notebooks are committed in)")
    args = parser.parse_args(argv)
    if args.check and args.clear:
        parser.error("--check and --clear exclude each other")

    root = Path(args.root).resolve()
    if not (root / "pyproject.toml").is_file():
        print(f"{root} does not look like the project root (no pyproject.toml)")
        return 2
    if args.clear:
        cell_source = EMPTY_SYNC_CELL
        print("emptying the sync cells")
    else:
        payload, digest, count = build_payload(root)
        cell_source = render_sync_cell(payload, digest, count)
        print(f"code hash {digest} | {count} files | {len(payload) / 1024:.0f} KB in the cell")

    stale = False
    notebooks = sorted(path for path in (root / "notebooks").rglob("*.ipynb") if ".ipynb_checkpoints" not in path.parts)
    for notebook in notebooks:
        status = update_notebook(notebook, cell_source, write=not args.check)
        if status == "updated":
            stale = True
            status = "STALE" if args.check else ("emptied" if args.clear else "updated")
        print(f"  {notebook.relative_to(root / 'notebooks').as_posix()}: {status}")
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
